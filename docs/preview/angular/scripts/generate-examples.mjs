import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const previewRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const root = resolve(previewRoot, '../../../packages/@fex-design/components/angular')
const entries = []
for (const layer of ['primitive', 'ui'])
  for (const component of await readdir(resolve(root, 'src', layer), { withFileTypes: true })) {
    if (!component.isDirectory()) continue
    try {
      for (const file of await readdir(resolve(root, 'src', layer, component.name, 'examples'), {
        withFileTypes: true,
      })) {
        if (!file.isFile() || !file.name.endsWith('.ts')) continue
        const source = resolve(root, 'src', layer, component.name, 'examples', file.name)
        const content = await readFile(source, 'utf8')
        const exported =
          content.match(/export class (\w+)/)?.[1] ?? content.match(/export \{ (\w+) \} from/)?.[1]
        if (exported)
          entries.push({
            key: `${layer}/${component.name}/${file.name.slice(0, -3)}`,
            exported,
            source,
          })
      }
    } catch {}
  }
entries.sort((a, b) => a.key.localeCompare(b.key))
const loaders = entries.map((entry) => {
  const path = relative(resolve(previewRoot, 'src'), entry.source)
    .split(sep)
    .join('/')
    .replace(/\.ts$/, '')
  const specifier = path.startsWith('.') ? path : './' + path
  return "  '" + entry.key + "': () => import('" + specifier + "').then((module) => module." + entry.exported + "),"
})
const output = resolve(previewRoot, 'src/examples.generated.ts')
await mkdir(dirname(output), { recursive: true })
await writeFile(
  output,
  `// Generated by scripts/generate-examples.mjs. Do not edit.\nimport type { Type } from '@angular/core'\n\nexport const examples: Record<string, () => Promise<Type<unknown>>> = {\n${loaders.join('\n')}\n}\n`,
)



