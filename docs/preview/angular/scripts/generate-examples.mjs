import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const retryableWriteCodes = new Set(['EBUSY', 'EPERM', 'EACCES', 'UNKNOWN'])

async function writeGeneratedFile(path, content) {
  try {
    if ((await readFile(path, 'utf8')) === content) return
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error
  }

  for (let attempt = 0; ; attempt += 1) {
    try {
      await writeFile(path, content)
      return
    } catch (error) {
      if (attempt >= 7 || !retryableWriteCodes.has(error?.code)) throw error
      await new Promise((resolve) => setTimeout(resolve, 25 * 2 ** attempt))
    }
  }
}

const previewRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const root = resolve(previewRoot, '../../../packages/@fex-design/angular/src')
const entries = []
for (const layer of ['primitive', 'ui'])
  for (const component of await readdir(resolve(root, layer), { withFileTypes: true })) {
    if (!component.isDirectory()) continue
    try {
      for (const file of await readdir(resolve(root, layer, component.name, 'examples'), {
        withFileTypes: true,
      })) {
        if (!file.isFile() || !file.name.endsWith('.ts')) continue
        const source = resolve(root, layer, component.name, 'examples', file.name)
        const content = await readFile(source, 'utf8')
        const exported =
          content.match(/export class (\w+)/)?.[1] ?? content.match(/export \{ (\w+) \} from/)?.[1]
        if (exported)
          entries.push({
            key: `${layer}/${component.name}/${file.name.slice(0, -3)}`,
            exported,
            source,
          })
      }
    } catch {}
  }
entries.sort((a, b) => a.key.localeCompare(b.key))
const loaders = entries.map((entry) => {
  const path = relative(resolve(previewRoot, 'src'), entry.source)
    .split(sep)
    .join('/')
    .replace(/\.ts$/, '')
  const importPath = path.startsWith('.') ? path : `./${path}`
  return `  '${entry.key}': () => import('${importPath}').then((module) => module.${entry.exported}),`
})
const output = resolve(previewRoot, 'src/examples.generated.ts')
await mkdir(dirname(output), { recursive: true })
const content = `// Generated by scripts/generate-examples.mjs. Do not edit.\nimport type { Type } from '@angular/core'\n\nexport const examples: Record<string, () => Promise<Type<unknown>>> = {\n${loaders.join('\n')}\n}\n`
await writeGeneratedFile(output, content)
