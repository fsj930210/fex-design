import fs from 'node:fs'
import path from 'node:path'

/**
 * Theme injection is generated from the design system's real sources so an
 * injected project always matches the repository theme (single source of truth).
 * Order matters: `@theme inline` must be top-level for Tailwind to process it;
 * token/theme declarations go inside `@layer base` so unlayered user styles win.
 */
const THEME_SOURCE_FILES = {
  themeInline: 'theme.css',
  tokens: 'tokens.css',
  light: 'themes/light.css',
  dark: 'themes/dark.css',
} as const

/** Present only after this generator has injected; legacy template lacks it. */
const GENERATED_MARKER = '@fex-design theme — generated by `fex init`'

export function buildThemeInjection(masterRepoRoot: string): string {
  const stylesSrc = path.join(masterRepoRoot, 'packages', '@fex-design', 'styles', 'src')
  const missing = Object.values(THEME_SOURCE_FILES).filter(
    (rel) => !fs.existsSync(path.join(stylesSrc, rel)),
  )
  if (missing.length > 0) {
    throw new Error(
      `Cannot generate theme: missing ${missing.join(', ')} under ${stylesSrc}. ` +
        '`fex init` must run with access to the fex-design repository.',
    )
  }
  const read = (rel: string): string =>
    fs.readFileSync(path.join(stylesSrc, rel), 'utf-8').trimEnd()

  return [
    `/* ${GENERATED_MARKER} from packages/@fex-design/styles; edit here to customize. */`,
    read(THEME_SOURCE_FILES.themeInline),
    '@layer base {',
    `/* packages/@fex-design/styles/src/${THEME_SOURCE_FILES.tokens} */`,
    read(THEME_SOURCE_FILES.tokens),
    `/* packages/@fex-design/styles/src/${THEME_SOURCE_FILES.light} */`,
    read(THEME_SOURCE_FILES.light),
    `/* packages/@fex-design/styles/src/${THEME_SOURCE_FILES.dark} */`,
    read(THEME_SOURCE_FILES.dark),
    '}',
  ].join('\n\n')
}

export function injectThemeVariables(
  targetDir: string,
  cssRelativePath: string,
  masterRepoRoot: string,
): boolean {
  const cssPath = path.join(targetDir, cssRelativePath)
  if (!fs.existsSync(cssPath)) {
    // If not found, try common CSS candidates
    const candidates = ['src/index.css', 'src/globals.css', 'src/App.css', 'src/main.css']
    for (const cand of candidates) {
      const p = path.join(targetDir, cand)
      if (fs.existsSync(p)) {
        return injectThemeVariables(targetDir, cand, masterRepoRoot)
      }
    }
    // If none exist, create the file
    fs.mkdirSync(path.dirname(cssPath), { recursive: true })
    fs.writeFileSync(cssPath, buildThemeInjection(masterRepoRoot), 'utf-8')
    return true
  }

  const existingContent = fs.readFileSync(cssPath, 'utf-8')
  if (existingContent.includes(GENERATED_MARKER)) {
    return false // Already injected by this generator
  }

  // Legacy shadcn-style template or a hand-rolled theme: append the real theme
  // so its declarations win by source order within the same layer/selector.
  const updated = existingContent.trimEnd() + '\n\n' + buildThemeInjection(masterRepoRoot)
  fs.writeFileSync(cssPath, updated, 'utf-8')
  return true
}
